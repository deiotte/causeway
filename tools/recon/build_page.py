#!/usr/bin/env python3
"""build_page.py — build tools/recon/recon.html from its source and the template.

    python3 tools/recon/build_page.py           # write recon.html
    python3 tools/recon/build_page.py --check   # exit 1 if recon.html is stale

The intake page carries templates/recon.md inside it and builds its form from
that text when it opens. It never restates the template: a form with its own
copy of the fields is a second contract, and two contracts drift (Build DNA §3,
"never silently fork"). This script is the only way the template gets in, and
tools/validate.py runs the check so a page that no longer matches the template
fails the build. ADR 0056.

Offline and dependency-free on purpose: the page must open from a USB stick on a
machine with no network, and the build must run where the standard's own tools
run.
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SOURCE = HERE / "recon.src.html"
TEMPLATE = ROOT / "templates" / "recon.md"
PAGE = HERE / "recon.html"
MARKER = "/*__RECON_TEMPLATE__*/"


def build() -> str:
    src = SOURCE.read_text(encoding="utf-8")
    if src.count(MARKER) != 1:
        raise SystemExit(f"{SOURCE.name}: expected exactly one {MARKER}")
    text = TEMPLATE.read_text(encoding="utf-8")
    # JSON inside a <script> element: escape "<" so no sequence in the template
    # can close the element or open a comment.
    payload = json.dumps(text, ensure_ascii=False).replace("<", "\\u003c")
    header = (
        "<!doctype html>\n"
        "<!-- GENERATED by tools/recon/build_page.py from tools/recon/recon.src.html\n"
        "     and templates/recon.md. Do not edit by hand. -->\n"
    )
    body = src.split("\n", 1)[1] if src.startswith("<!doctype html>") else src
    # The source's own "edit me" comment is replaced by the generated header.
    if body.startswith("<!--"):
        body = body.split("-->\n", 1)[1]
    return header + body.replace(MARKER, payload)


def main(argv: list[str]) -> int:
    page = build()
    if "--check" in argv:
        current = PAGE.read_text(encoding="utf-8") if PAGE.exists() else ""
        if current != page:
            print("tools/recon/recon.html is stale — run python3 tools/recon/build_page.py", file=sys.stderr)
            return 1
        print("tools/recon/recon.html current")
        return 0
    PAGE.write_text(page, encoding="utf-8")
    print(f"wrote {PAGE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
